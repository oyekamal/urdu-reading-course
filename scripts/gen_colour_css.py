#!/usr/bin/env python3
"""Generate the round-14 colour block (unit hues + tab bands + tinted surfaces, light + dark) and splice it into mobile/src/style.css
between the markers. Marko, the base teal/saffron/indigo and the feedback colours are NOT touched; this only adds colour to surfaces.
Research + measurements: research/20_colour_vibrancy.md.   python3 scripts/gen_colour_css.py"""
import re, pathlib
CSS = pathlib.Path(__file__).resolve().parent.parent / 'mobile/src/style.css'
# name, base, deep (white text >=4.5 / text on 14% wash >=4.5), ink on base, band gradient mode ('deep' = white text on deep->base, 'light' = navy text on base->lighter)
HUES = [('teal','#1E9C8F','#00756B','#FFFFFF','deep'),('saffron','#F2A93B','#8F5C14','#1E2F55','light'),('cobalt','#3566C8','#1F4FA3','#FFFFFF','deep'),
        ('plum','#7B52B5','#6A3D8F','#FFFFFF','deep'),('cerulean','#2CB1C7','#0B6F79','#1E2F55','light'),('leaf','#4F9E4B','#2F6A2C','#FFFFFF','deep'),('tangerine','#E8742E','#A94A12','#1E2F55','light')]
# tab colours are the ones the tab icons already use (learner.js TAB map): base, deep
TABS = {'today':('#1E9C8F','#126B62'),'units':('#F2A93B','#94590C'),'review':('#EF6B4F','#B03F22'),'read':('#4F5FD0','#2E3A8C'),'me':('#5FA55A','#2F6A2C'),'progress':('#5FA55A','#2F6A2C'),'more':('#D97AA6','#9C3A6A')}
def block():
    o = ["/* ===== round 14: colour (generated by scripts/gen_colour_css.py; research/20_colour_vibrancy.md) ===== */"]
    for n, (nm, b, d, i, mode) in enumerate(HUES):
        band = f"linear-gradient(120deg,{d},{b})" if mode == 'deep' else f"linear-gradient(120deg,{b},color-mix(in srgb,{b} 55%,#fff))"
        o.append(f".hue-{n}{{--ub:{b};--ud:{d};--ui:{i};--ux:{d};--uband:{band}}}")
    for t, (b, d) in TABS.items():
        o.append(f"body[data-tab='{t}']{{--tb:{b};--td:{d};--tband:linear-gradient(135deg,{d},color-mix(in srgb,{b} 85%,{d}))}}")
    o.append("@media (prefers-color-scheme:dark){")
    for n, (nm, b, d, i, mode) in enumerate(HUES):
        o.append(f" .hue-{n}{{--ub:color-mix(in srgb,{b} 78%,#1B2946);--ud:color-mix(in srgb,{b} 35%,#0B1426);--ui:#fff;--ux:color-mix(in srgb,{b} 50%,#fff);--uband:linear-gradient(120deg,color-mix(in srgb,{b} 40%,#0B1426),color-mix(in srgb,{b} 78%,#1B2946))}}")
    for t, (b, d) in TABS.items():
        o.append(f" body[data-tab='{t}']{{--tb:color-mix(in srgb,{b} 80%,#1B2946);--td:color-mix(in srgb,{b} 40%,#0B1426);--tband:linear-gradient(135deg,color-mix(in srgb,{b} 40%,#0B1426),color-mix(in srgb,{b} 70%,#1B2946))}}")
    o.append("}")
    o.append("""
#app{background:linear-gradient(180deg,color-mix(in srgb,var(--tb,#1E9C8F) 12%,var(--paper)) 0,var(--paper) 320px)}
.card{border-top:5px solid var(--tb,#1E9C8F);border-color:color-mix(in srgb,var(--tb,#1E9C8F) 25%,var(--line));background:color-mix(in srgb,var(--tb,#1E9C8F) 5%,var(--card))}
.card.unit{border-top-width:2px;border-color:color-mix(in srgb,var(--ub,#1E9C8F) 55%,var(--card));background:color-mix(in srgb,var(--ub,#1E9C8F) 8%,var(--card))}
.card.unit .unit-head{margin:0 0 12px;padding:16px 16px 14px;border-radius:0;background:var(--uband)}
.unit .unit-head .u-title,.unit .unit-head .u-ur,.unit .unit-head .u-count,.unit .unit-head b{color:var(--ui)!important}
.unit .unit-head .pill{background:rgba(255,255,255,.22);color:var(--ui)}
.unit.cur::before{display:none}
.unit .pearl.locked{background:color-mix(in srgb,var(--ub) 14%,var(--card));border:3px dashed color-mix(in srgb,var(--ub) 60%,var(--card));color:var(--ux)}
.unit .pearl.locked small{color:var(--ux)}
.unit .pearl.done{background:var(--ub);border-color:var(--ud);color:var(--ui)}
.page-head{background:var(--tband);margin:0 -12px 12px;padding:18px 14px 16px;border-radius:0 0 26px 26px;box-shadow:0 6px 16px color-mix(in srgb,var(--td) 30%,transparent)}
.page-head h1,.page-head .muted{color:#fff}.page-head .muted{opacity:.92}
.page-head .btn{background:#fff;color:var(--td);border-color:rgba(255,255,255,.7)}
@media (prefers-color-scheme:dark){.page-head .btn{background:var(--card);color:var(--ink);border-color:var(--line)}}
.btn-primary{background-image:linear-gradient(180deg,rgba(255,255,255,.2),rgba(255,255,255,0) 55%)}
.lesson{background:linear-gradient(180deg,color-mix(in srgb,var(--ub,#1E9C8F) 14%,var(--card)),color-mix(in srgb,var(--ub,#1E9C8F) 5%,var(--paper)) 70%)}
.lesson .blob{background:var(--ub,#1E9C8F)!important}
.lesson .blob .ur{color:var(--ui,#fff)!important;text-shadow:0 2px 0 rgba(0,0,0,.18)}
.lesson .lc-card{background:color-mix(in srgb,var(--ub,#1E9C8F) 8%,var(--card))}
.lesson .progress{background:color-mix(in srgb,var(--ub,#1E9C8F) 25%,var(--card))}
.bottom{border-top-color:color-mix(in srgb,var(--tb,#1E9C8F) 35%,var(--line))}""")
    o.append("/* ===== end round 14 colour ===== */")
    return "\n".join(o)
s = CSS.read_text()
b = block()
if '===== round 14: colour' in s: s = re.sub(r"/\* ===== round 14: colour.*?end round 14 colour ===== \*/", lambda m: b, s, flags=re.S)
else: s = s.rstrip() + "\n" + b + "\n"
CSS.write_text(s); print('colour block written,', len(b), 'bytes')
